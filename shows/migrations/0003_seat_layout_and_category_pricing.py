def backwards(apps, schema_editor):
    connection = schema_editor.connection
    Cinema = apps.get_model("cinema", "Cinema")
    cinemas = list(Cinema.objects.using(connection.alias).all())
    schemas = (
        [cinema.schema_name for cinema in cinemas]
        if connection.vendor == "postgresql"
        else ["public"]
    )

    original_search_path = None
    if connection.vendor == "postgresql":
        with connection.cursor() as cursor:
            cursor.execute("SELECT current_setting('search_path')")
            original_search_path = cursor.fetchone()[0]

    try:
        for schema_name in schemas:
            if not table_exists(connection, schema_name, "shows_seat"):
                continue
            set_search_path(connection, schema_name)

            quote = connection.ops.quote_name
            if connection.vendor == "postgresql":
                qualified_seat_table = (
                    f"{quote(schema_name)}.{quote('shows_seat')}"
                )
                qualified_price_table = (
                    f"{quote(schema_name)}.{quote('shows_screenseatprice')}"
                )
            else:
                qualified_seat_table = quote("shows_seat")
                qualified_price_table = quote("shows_screenseatprice")

            with connection.cursor() as cursor:
                cursor.execute(f"DROP TABLE IF EXISTS {qualified_price_table}")
                cursor.execute(
                    f"DROP INDEX IF EXISTS {quote('unique_seat_position_per_row')}"
                )
                cursor.execute(
                    f"UPDATE {qualified_seat_table} "
                    f"SET {quote('seat_type')} = %s "
                    f"WHERE {quote('seat_type')} IN (%s, %s, %s)",
                    ["STANDARD", "NORMAL", "EXECUTIVE", "RECLINER"],
                )
            if "position" in seat_columns(connection, "shows_seat"):
                with connection.schema_editor() as editor:
                    Seat = apps.get_model("shows", "Seat")
                    field = models.PositiveSmallIntegerField(
                        null=True,
                        blank=True,
                    )
                    field.set_attributes_from_name("position")
                    field.model = Seat
                    editor.remove_field(Seat, field)
    finally:
        if original_search_path is not None:
            with connection.cursor() as cursor:
                cursor.execute(
                    "SELECT set_config('search_path', %s, false)",
                    [original_search_path],
                )


