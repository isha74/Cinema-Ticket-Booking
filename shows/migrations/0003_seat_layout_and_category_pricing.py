from django.db import migrations, models
import django.db.models.deletion


def set_search_path(connection, schema_name):
    if connection.vendor != "postgresql":
        return
    quoted_schema = connection.ops.quote_name(schema_name)
    with connection.cursor() as cursor:
        cursor.execute(
            "SELECT set_config('search_path', %s, false)",
            [f"{quoted_schema}, public"],
        )


def table_exists(connection, schema_name, table_name):
    if connection.vendor == "postgresql":
        quoted_schema = connection.ops.quote_name(schema_name)
        quoted_table = connection.ops.quote_name(table_name)
        with connection.cursor() as cursor:
            cursor.execute(
                "SELECT to_regclass(%s)",
                [f"{quoted_schema}.{quoted_table}"],
            )
            return cursor.fetchone()[0] is not None

    return table_name in connection.introspection.table_names()


def seat_columns(connection, table_name):
    with connection.cursor() as cursor:
        return {
            column.name
            for column in connection.introspection.get_table_description(
                cursor,
                table_name,
            )
        }


def add_position_column(connection, schema_name):
    if connection.vendor == "postgresql":
        quoted_schema = connection.ops.quote_name(schema_name)
        qualified_table = (
            f"{quoted_schema}.{connection.ops.quote_name('shows_seat')}"
        )
    else:
        qualified_table = connection.ops.quote_name("shows_seat")

    with connection.cursor() as cursor:
        cursor.execute(
            f"ALTER TABLE {qualified_table} "
            f"ADD COLUMN {connection.ops.quote_name('position')} smallint"
        )


def create_price_table(connection, schema_name):
    quote = connection.ops.quote_name
    if connection.vendor == "postgresql":
        quoted_schema = quote(schema_name)
        price_table = f"{quoted_schema}.{quote('shows_screenseatprice')}"
        screen_table = f"{quoted_schema}.{quote('shows_screen')}"
        id_column = "bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY"
        index_name = quote("shows_screenseatprice_screen_id_idx")
    else:
        price_table = quote("shows_screenseatprice")
        screen_table = quote("shows_screen")
        id_column = "integer PRIMARY KEY AUTOINCREMENT"
        index_name = quote("shows_screenseatprice_screen_id_idx")

    with connection.cursor() as cursor:
        cursor.execute(
            f"CREATE TABLE IF NOT EXISTS {price_table} ("
            f"{quote('id')} {id_column}, "
            f"{quote('screen_id')} bigint NOT NULL "
            f"REFERENCES {screen_table} ({quote('id')}) "
            "ON DELETE CASCADE DEFERRABLE INITIALLY DEFERRED, "
            f"{quote('seat_type')} varchar(20) NOT NULL, "
            f"{quote('price')} numeric(8, 2) NOT NULL "
            "CHECK (price > 0), "
            "CONSTRAINT unique_screen_seat_type_price "
            f"UNIQUE ({quote('screen_id')}, {quote('seat_type')})"
            ")"
        )
        cursor.execute(
            f"CREATE INDEX IF NOT EXISTS {index_name} "
            f"ON {price_table} ({quote('screen_id')})"
        )
        position_index = quote("unique_seat_position_per_row")
        if connection.vendor == "postgresql":
            seat_table = f"{quoted_schema}.{quote('shows_seat')}"
        else:
            seat_table = quote("shows_seat")
        cursor.execute(
            f"CREATE UNIQUE INDEX IF NOT EXISTS {position_index} "
            f"ON {seat_table} ({quote('screen_id')}, {quote('row')}, "
            f"{quote('position')}) WHERE {quote('position')} IS NOT NULL"
        )


